"""Generate the responsive Memo images and their Vite imports using Pillow."""

from pathlib import Path

from PIL import Image, ImageOps


root = Path(__file__).resolve().parents[1]
output = root / "assets/about"
output.mkdir(parents=True, exist_ok=True)
originals = {
    "shore": "assets/optimized/shots-000041000021.webp",
    "blueCar": "assets/optimized/shots-000041000013.webp",
    "field": "assets/optimized/shots-000041040008.webp",
    "cafe": "assets/about-cafe-reference.jpg",
    "landscape": "assets/optimized/shots-000041000008.webp",
}

imports = []
entries = []
for name, source in originals.items():
    with Image.open(root / source) as source_image:
        image = ImageOps.exif_transpose(source_image).convert("RGB")
    width, height = image.size
    widths = sorted({min(size, width) for size in (320, 480, 640, 960)})
    candidates = []
    for size in widths:
        preview = image.resize((size, round(height * size / width)), Image.Resampling.LANCZOS)
        filename = f"{name}-{size}.webp"
        preview.save(output / filename, quality=75, method=6)
        identifier = f"{name}{size}"
        imports.append(f'import {identifier} from "../assets/about/{filename}";')
        candidates.append(f"${{{identifier}}} {size}w")

    entries.append(
        f"  {name}: {{ src: {name}{min(640, width)}, srcSet: `{', '.join(candidates)}`, "
        f"width: {width}, height: {height} }},"
    )

manifest = [
    "// Generated by scripts/optimize-about-photos.py.",
    *imports, "", "export const aboutPhotoAssets = {", *entries, "};", "",
]
(root / "src/about-photo-assets.js").write_text("\n".join(manifest), encoding="utf-8")
