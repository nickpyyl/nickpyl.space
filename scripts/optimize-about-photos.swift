import Foundation
import ImageIO
import UniformTypeIdentifiers

let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
let output = root.appendingPathComponent("assets/about")
try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)

let originals = [
    ("parkedCar", "assets/optimized/shots-000032420024.webp"),
    ("passenger", "assets/about-car-portrait-reference.jpg"),
    ("hillside", "assets/optimized/shots-000041030012.webp"),
    ("boat", "assets/optimized/shots-000041030015.webp"),
    ("shore", "assets/optimized/shots-000041000021.webp"),
]

var imports: [String] = []
var entries: [String] = []
var originalBytes = 0
var totals: [Int: Int] = [:]

for (name, path) in originals {
    let input = root.appendingPathComponent(path)
    let source = CGImageSourceCreateWithURL(input as CFURL, nil)!
    let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil)! as NSDictionary
    let sourceWidth = properties[kCGImagePropertyPixelWidth] as! Int
    let sourceHeight = properties[kCGImagePropertyPixelHeight] as! Int
    originalBytes += try input.resourceValues(forKeys: [.fileSizeKey]).fileSize!
    let widths = Array(Set([480, 800, 1200].map { min($0, sourceWidth) })).sorted()
    var candidates: [String] = []

    for width in widths {
        let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: width,
        ] as CFDictionary)!
        let filename = "\(name)-\(image.width).jpg"
        let destinationURL = output.appendingPathComponent(filename)
        let destination = CGImageDestinationCreateWithURL(destinationURL as CFURL, UTType.jpeg.identifier as CFString, 1, nil)!
        CGImageDestinationAddImage(destination, image, [
            kCGImageDestinationLossyCompressionQuality: 0.5,
            kCGImagePropertyJFIFDictionary: [kCGImagePropertyJFIFIsProgressive: true],
        ] as CFDictionary)
        precondition(CGImageDestinationFinalize(destination), "Could not write \(filename)")
        let bytes = try destinationURL.resourceValues(forKeys: [.fileSizeKey]).fileSize!
        totals[width, default: 0] += bytes
        let identifier = "\(name)\(image.width)"
        imports.append("import \(identifier) from \"../assets/about/\(filename)\";")
        candidates.append("${\(identifier)} \(image.width)w")
        print("\(filename): \(bytes) bytes")
    }

    let fallback = widths.contains(800) ? 800 : widths.last!
    entries.append("  \(name): { src: \(name)\(fallback), srcSet: `\(candidates.joined(separator: ", "))`, width: \(sourceWidth), height: \(sourceHeight) },")
}

let manifest = "// Generated by scripts/optimize-about-photos.swift.\n" + imports.joined(separator: "\n")
    + "\n\nexport const aboutPhotoAssets = {\n" + entries.joined(separator: "\n") + "\n};\n"
try manifest.write(to: root.appendingPathComponent("src/about-photo-assets.js"), atomically: true, encoding: .utf8)
print("Original total: \(originalBytes) bytes")
print("Variant totals: \(totals)")
